# @option --output <PATH>                Output file path (default: ./cheatsheet.{format})
# @option --template <PATH>              Custom template file path
# @option --author <STRING>              Author name for the cheat sheet
# @option --version <STRING>             Version number (default: 1.0.0)
# @option --columns <INTEGER>            Number of columns for layout (default: 2)
# @option --max-width <INTEGER>          Maximum width in characters (default: 80)
# @flag   --include-toc                  Include table of contents
# @flag   --number-sections              Number sections automatically
# @flag   --highlight-syntax             Enable syntax highlighting for code blocks
# @flag   --compact                      Use compact layout (less whitespace)
